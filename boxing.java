public class boxing {
    public static void main(String[] args) {
        int x = 10;
        int obj1 = x;

        int y = 10;
        Integer obj2 = y;

        System.out.println("Value of obj1: " + obj1);
        System.out.println("Value of obj2: " + obj2);

        Integer obj3 = 50;
        int z = obj3;

        Integer obj4 = 100;
        int w = obj4;

        System.out.println("Value of z: " + z);
        System.out.println("Value of w: " + w);
    }
}
